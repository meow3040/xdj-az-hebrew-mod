"""hebrew-assets.py: generate the data headers of the Hebrew mod (src/azmod/hebrew.c).

  python3 tools/hebrew-assets.py --font DejaVuSans-Bold.ttf --ucd UCD_DIR

writes three plain-data headers into src/azmod/:

  heb_glyphs.h   the outlines of the Hebrew letters, punctuation and presentation forms, and
                 the new shekel sign, taken from DejaVu Sans Bold (DejaVu fonts license, see
                 NOTICE). EP147's own faces have none of them; hebrew.c hands these to JUCE
                 through FreeType when a face has no glyph of its own for the character.
                 Points are in the donor's font units, exactly as FreeType loads the glyph
                 unscaled (left side bearing applied); Hebrew points (niqqud) and cantillation
                 marks are listed with no outline and no advance, so they draw as nothing.
  heb_keys.h     the Hebrew page of the search keyboard: 27 letters plus the EN and HE page
                 keys, each in three states (normal, pressed, disabled), as RGBA PNGs drawn
                 in the keyboard's own checkered style with the same font.
  bidi_tables.h  the Unicode Bidi_Class of every code point that is not L (ranges), the
                 Bidi_Mirroring_Glyph pairs and the Bidi_Paired_Bracket pairs, for
                 bidi_logic.h. The classes come from this Python's unicodedata; UCD_DIR must
                 hold BidiBrackets.txt and BidiMirroring.txt of the same Unicode version
                 (https://www.unicode.org/Public/<version>/ucd/).

Needs fontTools and Pillow (pip install fonttools pillow). The output depends only on the
inputs: the same font, UCD files and Python Unicode version give the same headers.
"""
import argparse, io, os, re, sys, unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "src", "azmod")

# ---------------------------------------------------------------- glyphs
# Spacing characters drawn from the donor. Letters, maqaf, paseq, sof pasuq, nun hafukha,
# the Yiddish ligatures, geresh and gershayim, the presentation forms (letters with dagesh,
# shin and sin dots, wide letters), and the new shekel sign.
SPACING = (list(range(0x05D0, 0x05EB)) + [0x05BE, 0x05C0, 0x05C3, 0x05C6] +
           list(range(0x05EF, 0x05F5)) + list(range(0xFB1D, 0xFB50)) + [0x20AA])


def is_mark(cp):
    return unicodedata.category(chr(cp)) in ("Mn", "Me")


def glyph_records(font_path):
    from fontTools.ttLib import TTFont
    font = TTFont(font_path)
    upm = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    glyf, hmtx = font["glyf"], font["hmtx"]
    recs = []
    for cp in sorted(set(SPACING) | {c for c in range(0x0591, 0x05C8) if is_mark(c)}):
        if is_mark(cp):
            if unicodedata.category(chr(cp)) != "Cn":
                recs.append((cp, 0, [], [], []))
            continue
        name = cmap.get(cp)
        if name is None:  # a presentation form the donor lacks: its base letter
            base = unicodedata.decomposition(chr(cp)).split()
            base = [b for b in base if not b.startswith("<")]
            name = cmap.get(int(base[0], 16)) if base else None
            if name is None:
                continue
        g = glyf[name]
        coords, ends, flags = g.getCoordinates(glyf)
        adv, lsb = hmtx[name]
        pts = [(int(x), int(y)) for x, y in coords]
        shift = 0
        if pts:
            shift = lsb - min(x for x, _ in pts)  # FreeType puts the origin lsb left of xMin
        pts = [(x + shift, y) for x, y in pts]
        tags = [1 if f & 1 else 0 for f in flags]
        recs.append((cp, adv, pts, tags, list(ends)))
    return upm, recs


def write_glyphs(font_path):
    upm, recs = glyph_records(font_path)
    out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
           "/* GENERATED by tools/hebrew-assets.py from DejaVu Sans Bold (DejaVu fonts license, NOTICE).",
           " * Do not edit. The glyphs hebrew.c gives EP147's faces for the Hebrew characters they lack:",
           " * per character its advance and, from pt0, npts points (font units, origin as FreeType loads",
           " * the glyph unscaled), each on the curve (tag 1) or a quadratic control point (tag 0), in",
           " * ncont contours ending at the ends[] indices (relative to pt0). A mark has no point and no",
           " * advance. Sorted by code point. */",
           "#define HEB_DONOR_UPM %d" % upm,
           "struct heb_glyph {",
           "    unsigned short cp, adv, pt0, npts, ct0, ncont;",
           "    short xmin, ymin, xmax, ymax;",
           "};"]
    gl, pts, tags, ends = [], [], [], []
    for cp, adv, p, t, e in recs:
        if p:
            xs, ys = [x for x, _ in p], [y for _, y in p]
            bb = (min(xs), min(ys), max(xs), max(ys))
        else:
            bb = (0, 0, 0, 0)
        gl.append("    {0x%04x, %d, %d, %d, %d, %d, %d, %d, %d, %d}, /* %s */" %
                  ((cp, adv, len(pts), len(p), len(ends), len(e)) + bb +
                   (unicodedata.name(chr(cp), "U+%04X" % cp).lower(),)))
        pts += p
        tags += t
        ends += e
    out.append("static const struct heb_glyph HEB_GLYPHS[%d] = {" % len(gl))
    out += gl
    out.append("};")

    def rows(items, per):
        return ["    " + ", ".join(items[i:i + per]) + "," for i in range(0, len(items), per)]
    out.append("static const short HEB_PTS[%d][2] = {" % len(pts))
    out += rows(["{%d, %d}" % xy for xy in pts], 8)
    out.append("};")
    out.append("static const unsigned char HEB_TAGS[%d] = {" % len(tags))
    out += rows([str(t) for t in tags], 32)
    out.append("};")
    out.append("static const unsigned short HEB_ENDS[%d] = {" % len(ends))
    out += rows([str(e) for e in ends], 20)
    out.append("};")
    return out


# ---------------------------------------------------------------- keyboard art
# The search keyboard's Hebrew page (compact layout: q holds tav, w final tsadi; the
# otherwise hidden shift key holds final pe), then the page keys: EN on the Hebrew page's
# 123 key, HE on the numbers page's ABC key.
KEY_LABELS = list("תץקראטוןםפשדגכעיחלךזסבהנמצף") + ["EN", "HE"]


def key_png(font_path, label, width, state):
    from PIL import Image, ImageDraw, ImageFilter, ImageFont
    im = Image.new("RGBA", (width, 94))
    if state != 2:
        mask = Image.new("L", im.size)
        ImageDraw.Draw(mask).rectangle((10, 10, width - 11, 83), fill=170)
        im.putalpha(mask.filter(ImageFilter.GaussianBlur(5)))
    dark, light = ((35, 50), (100, 115), (26, 39))[state]
    for y in range(10, 84):
        for x in range(10, width - 10):
            c = light if (x // 4 + y // 4) % 2 == 0 else dark
            im.putpixel((x, y), (c, c, c, 255))
    d = ImageDraw.Draw(im)
    edge = 225 if state == 1 else dark
    d.rectangle((10, 10, width - 11, 83), outline=(edge, edge, edge, 255), width=1)
    font = ImageFont.truetype(font_path, 32)
    box = d.textbbox((0, 0), label, font=font)
    d.text(((width - box[2] + box[0]) / 2 - box[0], (94 - box[3] + box[1]) / 2 - box[1]), label,
           font=font, fill=(88, 88, 88, 255) if state == 2 else (255, 255, 255, 255))
    raw = io.BytesIO()
    im.save(raw, format="PNG", optimize=True)
    return raw.getvalue()


def write_keys(font_path):
    out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
           "/* GENERATED by tools/hebrew-assets.py (DejaVu Sans Bold, DejaVu fonts license, NOTICE).",
           " * Do not edit. The search keyboard's Hebrew page. Key k (0-25) is the stock key named",
           " * HEB_KEY_QWERTY[k] and types HEB_KEY_CP[k]; key 26 is the stock (hidden) shift key and types",
           " * HEB_KEY_CP[26]. HEB_KEY_PNG[key * 3 + state]: key 0-26 those letters, 27 = EN, 28 = HE;",
           " * state 0 normal, 1 pressed, 2 disabled. RGBA PNGs 110x94 (EN, HE: 140x94), the size of",
           " * EP147's own key images. */",
           "#define HEB_KEYS_N %d" % len(KEY_LABELS),
           "#define HEB_KEY_QWERTY \"qwertyuiopasdfghjklzxcvbnm\"",
           "static const unsigned short HEB_KEY_CP[27] = {",
           "    " + ", ".join("0x%04x" % ord(c) for c in KEY_LABELS[:27]) + ",",
           "};"]
    names = []
    for i, label in enumerate(KEY_LABELS):
        for state in range(3):
            data = key_png(font_path, label, 140 if i >= 27 else 110, state)
            n = "heb_key_%d_%d" % (i, state)
            names.append(n)
            out.append("static const unsigned char %s[%d] = {" % (n, len(data)))
            vals = [str(b) for b in data]
            out += ["    " + ",".join(vals[j:j + 24]) + "," for j in range(0, len(vals), 24)]
            out.append("};")
    out.append("static const struct {")
    out.append("    const unsigned char *png;")
    out.append("    int len;")
    out.append("} HEB_KEY_PNG[%d] = {" % len(names))
    out += ["    {%s, (int) sizeof %s}," % (n, n) for n in names]
    out.append("};")
    return out


# ---------------------------------------------------------------- bidi tables
CLASSES = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON",
           "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]
# DerivedBidiClass.txt's defaults for unassigned code points (Unicode 16)
DEFAULT_R = [(0x0590, 0x05FF), (0x07C0, 0x085F), (0xFB1D, 0xFB4F), (0x10800, 0x10CFF),
             (0x10D40, 0x10EBF), (0x10F00, 0x10F2F), (0x10F70, 0x10FFF), (0x1E800, 0x1EC6F),
             (0x1ECC0, 0x1ECFF), (0x1ED50, 0x1EDFF), (0x1EF00, 0x1EFFF)]
DEFAULT_AL = [(0x0600, 0x07BF), (0x0860, 0x08FF), (0xFB50, 0xFDCF), (0xFDF0, 0xFDFF),
              (0xFE70, 0xFEFF), (0x10D00, 0x10D3F), (0x10EC0, 0x10EFF), (0x10F30, 0x10F6F),
              (0x1EC70, 0x1ECBF), (0x1ED00, 0x1ED4F), (0x1EE00, 0x1EEFF)]
DEFAULT_ET = [(0x20A0, 0x20CF)]


def default_class(cp):
    for lo, hi in DEFAULT_R:
        if lo <= cp <= hi:
            return "R"
    for lo, hi in DEFAULT_AL:
        if lo <= cp <= hi:
            return "AL"
    for lo, hi in DEFAULT_ET:
        if lo <= cp <= hi:
            return "ET"
    if (0xFDD0 <= cp <= 0xFDEF or (cp & 0xFFFE) == 0xFFFE or 0xE0000 <= cp <= 0xE0FFF or
            0x2060 <= cp <= 0x206F or 0xFFF0 <= cp <= 0xFFF8 or 0x1BCA0 <= cp <= 0x1BCA3):
        return "BN"  # noncharacters and default ignorables
    return "L"


def ucd_pairs(path, want_version):
    text = open(path, encoding="utf-8").read()
    m = re.search(r"#\s*\w+-(\d+\.\d+\.\d+)\.txt", text)
    if not m or m.group(1) != want_version:
        sys.exit("%s is Unicode %s, this Python's unicodedata is %s" %
                 (path, m.group(1) if m else "?", want_version))
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            yield [f.strip() for f in line.split(";")]


def write_bidi(ucd):
    ver = unicodedata.unidata_version
    ranges = []
    for cp in range(0x110000):
        c = unicodedata.bidirectional(chr(cp)) or default_class(cp)
        if c not in CLASSES:
            sys.exit("unknown bidi class %s at U+%04X" % (c, cp))
        if c == "L":
            continue
        if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == c:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp, c])
    mirror = sorted((int(a, 16), int(b, 16))
                    for a, b in ucd_pairs(os.path.join(ucd, "BidiMirroring.txt"), ver))
    brackets = sorted((int(a, 16), int(b, 16), t)
                      for a, b, t in ucd_pairs(os.path.join(ucd, "BidiBrackets.txt"), ver))
    out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
           "/* GENERATED by tools/hebrew-assets.py from the Unicode Character Database %s. Do not edit." % ver,
           " * BIDI_RANGES: every code point whose Bidi_Class is not L, as {first, last | class << 24}",
           " * (the bidi_class enum of bidi_logic.h), sorted. BIDI_MIRROR: Bidi_Mirroring_Glyph,",
           " * {code point, mirror}. BIDI_BRACKET: Bidi_Paired_Bracket, {code point, pair, 1 = opening}. */",
           "static const unsigned BIDI_RANGES[%d][2] = {" % len(ranges)]
    items = ["{0x%x, 0x%x | BIDI_%s << 24}" % (lo, hi, c) for lo, hi, c in ranges]
    out += ["    " + ", ".join(items[i:i + 3]) + "," for i in range(0, len(items), 3)]
    out.append("};")
    out.append("static const unsigned BIDI_MIRROR[%d][2] = {" % len(mirror))
    items = ["{0x%x, 0x%x}" % m for m in mirror]
    out += ["    " + ", ".join(items[i:i + 6]) + "," for i in range(0, len(items), 6)]
    out.append("};")
    out.append("static const unsigned BIDI_BRACKET[%d][3] = {" % len(brackets))
    items = ["{0x%x, 0x%x, %d}" % (a, b, t == "o") for a, b, t in brackets]
    out += ["    " + ", ".join(items[i:i + 5]) + "," for i in range(0, len(items), 5)]
    out.append("};")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--font", required=True, help="DejaVuSans-Bold.ttf")
    ap.add_argument("--ucd", required=True, help="directory with BidiBrackets.txt and BidiMirroring.txt")
    a = ap.parse_args()
    for name, lines in (("heb_glyphs.h", write_glyphs(a.font)), ("heb_keys.h", write_keys(a.font)),
                        ("bidi_tables.h", write_bidi(a.ucd))):
        with open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
        print("wrote src/azmod/%s" % name)


if __name__ == "__main__":
    main()
